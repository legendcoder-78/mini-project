"""Shared Pydantic Schemas for MLOps Weather Early Warning System.

Defines strict Pydantic v2 data contracts used across:
- Services Ingestion (telemetry replay producer)
- Services Common (Redis buffer)
- Inference API & Worker (streaming hazard prediction)
- Drift Monitor (statistical shift evaluation)
- Dashboard (Streamlit live telemetry visualization)
"""

from datetime import datetime, timezone
from typing import Any, Dict, Optional
import uuid

from pydantic import (
    AliasChoices,
    BaseModel,
    ConfigDict,
    Field,
    field_validator,
)

# Standard meteorological features required for model inference & drift scoring
REQUIRED_FEATURE_KEYS = {
    "rainfall_mm",
    "soil_moisture",
    "temperature_c",
    "humidity_pct",
    "wind_speed_kmh",
}


class BaseEvent(BaseModel):
    """Base schema providing standardized JSON serialization helpers."""

    model_config = ConfigDict(
        extra="ignore",
        populate_by_name=True,
        validate_assignment=True,
    )

    def to_dict(self) -> Dict[str, Any]:
        """Serialize event to Python dictionary."""
        return self.model_dump()

    def to_json(self) -> str:
        """Serialize event to JSON string."""
        return self.model_dump_json()

    @classmethod
    def from_dict(cls, data: Dict[str, Any]):
        """Deserialize from Python dictionary."""
        return cls.model_validate(data)

    @classmethod
    def from_json(cls, json_str: str):
        """Deserialize from JSON string."""
        return cls.model_validate_json(json_str)


class TelemetryEvent(BaseEvent):
    """Raw meteorological and environmental telemetry event.

    Emitted by IoT weather sensor simulation and published to 'raw-telemetry' topic.
    """

    event_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique UUID identifier for this telemetry event",
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="ISO-8601 UTC timestamp of observation",
    )
    lat: float = Field(
        ...,
        ge=-90.0,
        le=90.0,
        validation_alias=AliasChoices("lat", "latitude"),
        description="Latitude in decimal degrees (-90 to 90)",
    )
    lon: float = Field(
        ...,
        ge=-180.0,
        le=180.0,
        validation_alias=AliasChoices("lon", "longitude"),
        description="Longitude in decimal degrees (-180 to 180)",
    )
    zone_id: str = Field(
        ...,
        min_length=1,
        description="Geospatial micro-climate zone identifier (e.g. ZONE_KODAGU)",
    )
    features: Dict[str, float] = Field(
        ...,
        description="Dictionary mapping meteorological feature names to numerical values",
    )
    delayed_label: Optional[int] = Field(
        default=None,
        ge=0,
        le=1,
        description="Optional ground-truth hazard verification label (0 or 1)",
    )

    @field_validator("timestamp")
    @classmethod
    def validate_timestamp(cls, v: str) -> str:
        if not v or not isinstance(v, str) or not v.strip():
            raise ValueError("Timestamp must be a non-empty ISO-8601 string")
        return v.strip()

    @field_validator("zone_id")
    @classmethod
    def validate_zone_id(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("zone_id cannot be empty or whitespace")
        return v.strip()

    @field_validator("features")
    @classmethod
    def validate_features(cls, v: Dict[str, Any]) -> Dict[str, float]:
        if not isinstance(v, dict):
            raise ValueError("Features must be a dictionary")

        missing_keys = REQUIRED_FEATURE_KEYS - set(v.keys())
        if missing_keys:
            raise ValueError(
                f"Missing required feature keys: {sorted(list(missing_keys))}. "
                f"Required features are: {sorted(list(REQUIRED_FEATURE_KEYS))}"
            )

        cleaned_features: Dict[str, float] = {}
        for key, val in v.items():
            if val is None:
                raise ValueError(f"Feature '{key}' cannot be None")
            try:
                cleaned_features[key] = float(val)
            except (ValueError, TypeError) as exc:
                raise ValueError(
                    f"Feature '{key}' must be a numerical float, got {val!r}"
                ) from exc

        return cleaned_features


class PredictionEvent(BaseEvent):
    """Inference result generated by the hazard classification model.

    Published to 'predictions-log' Kafka topic.
    """

    event_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="UUID reference corresponding to the originating TelemetryEvent",
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="ISO-8601 UTC timestamp of inference generation",
    )
    lat: float = Field(
        ...,
        ge=-90.0,
        le=90.0,
        validation_alias=AliasChoices("lat", "latitude"),
        description="Latitude in decimal degrees",
    )
    lon: float = Field(
        ...,
        ge=-180.0,
        le=180.0,
        validation_alias=AliasChoices("lon", "longitude"),
        description="Longitude in decimal degrees",
    )
    zone_id: str = Field(
        ...,
        min_length=1,
        description="Spatial zone ID",
    )
    predicted_label: int = Field(
        ...,
        ge=0,
        le=1,
        description="Binary hazard prediction: 0 (Normal) or 1 (Extreme Hazard)",
    )
    hazard_probability: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Calibrated probability of severe convective hazard",
    )
    model_version: str = Field(
        ...,
        min_length=1,
        description="MLflow model version or checkpoint tag (e.g. v1)",
    )
    inference_latency_ms: float = Field(
        ...,
        ge=0.0,
        description="Model inference execution latency in milliseconds",
    )


class DriftAlertEvent(BaseEvent):
    """Statistical distribution drift alert event.

    Published to 'drift-alerts' Kafka topic when KS or PSI thresholds are breached.
    """

    alert_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique UUID identifier for this drift alert",
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="ISO-8601 UTC timestamp when drift condition was detected",
    )
    zone_id: str = Field(
        ...,
        min_length=1,
        description="Spatial zone ID exhibiting statistical distribution drift",
    )
    psi_scores: Dict[str, float] = Field(
        ...,
        description="Population Stability Index (PSI) per feature",
    )
    ks_pvalues: Dict[str, float] = Field(
        ...,
        description="Two-sample Kolmogorov-Smirnov test p-values per feature",
    )
    max_psi: float = Field(
        ...,
        ge=0.0,
        description="Maximum observed PSI among all analyzed features",
    )
    min_pvalue: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Minimum observed KS test p-value among all analyzed features",
    )
    drift_detected: bool = Field(
        ...,
        description="True if any feature breached drift thresholds",
    )
    retrain_triggered: bool = Field(
        ...,
        description="True if an automated retraining trigger was dispatched to Airflow",
    )
